#!/usr/bin/env python3
"""Reproduce the pinned instrument verbatim in the thesis appendix (GUIDE-LLM item C.1).

Reads the two model-facing artefacts named in pipeline/pins.json -- the rendered system
prompt and the tool configuration of the registered instrument v1.0 -- verifies their
sha256 against the pins, and writes paper/tables/instrument_appendix.tex: the artefact
text LaTeX-escaped line by line, nothing reworded, nothing omitted. The header of the
output names both digests, so the appendix is bound to the artefacts the production run
used. `--check` re-renders in memory and compares with the file on disk, as figures.py
does for the tables.

Runs under either interpreter; standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent          # tools/pipeline
TOOLS = HERE.parent                              # tools
REPO = TOOLS.parent
PINS = HERE / "pins.json"
OUT = REPO / "paper" / "tables" / "instrument_appendix.tex"

# Every ASCII special is emitted by its character code, which is encoding-independent inside the
# typewriter font (OT1 has no \textquotedbl, \textquotesingle or \textasciigrave); the dashes and
# curly quotes, which the typewriter font lacks at their OT1 positions, are set in the roman font.
_ESC = {
    "\\": r"{\char92}", "{": r"{\char123}", "}": r"{\char125}", "$": r"\$", "&": r"\&",
    "#": r"\#", "_": r"\_", "%": r"\%", "~": r"{\char126}", "^": r"{\char94}",
    "`": r"{\char96}", "'": r"{\char39}", '"': r"{\char34}",
    "<": r"{\char60}", ">": r"{\char62}", "|": r"{\char124}",
    "\u2014": r"{\rmfamily---}", "\u2013": r"{\rmfamily--}",
    "\u201c": r"{\rmfamily``}", "\u201d": r"{\rmfamily''}",
    "\u2018": r"{\rmfamily`}", "\u2019": r"{\rmfamily'}", "\u201e": r"{\rmfamily,,}",
    "\u2026": r"{\rmfamily\ldots}", "\u00d7": r"{\rmfamily$\times$}",
    "\u2192": r"{\rmfamily$\rightarrow$}", "\u2265": r"{\rmfamily$\geq$}", "\u2264": r"{\rmfamily$\leq$}",
    "\u00b7": r"{\rmfamily$\cdot$}", "\u2022": r"{\rmfamily$\bullet$}",
}


def escape(line: str) -> str:
    """One artefact line as LaTeX: special characters escaped, leading spaces kept as ~."""
    stripped = line.lstrip(" ")
    indent = len(line) - len(stripped)
    body = "".join(_ESC.get(ch, ch) for ch in stripped)
    return "~" * indent + body


def block(text: str) -> str:
    lines = []
    for raw in text.splitlines():
        if raw.strip():
            lines.append(escape(raw) + r"\par")
        else:
            lines.append(r"\medskip")
    return "\n".join(lines)


def load_pin(pins: dict, key: str) -> tuple[Path, str, bytes]:
    pin = pins[key]
    path = TOOLS / pin["path"]
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != pin["sha256"]:
        sys.exit(f"{key}: {path} has sha256 {digest}, pins.json expects {pin['sha256']}")
    return path, digest, raw


def render(today: str) -> str:
    pins = json.loads(PINS.read_text(encoding="utf-8"))
    p_path, p_sha, p_raw = load_pin(pins, "system_prompt")
    t_path, t_sha, t_raw = load_pin(pins, "tool_config")
    cb = pins["codebook"]
    head = (
        f"% Generated by tools/pipeline/render_instrument_appendix.py on {today} from the pinned artefacts\n"
        f"% {p_path.relative_to(REPO)} (sha256 {p_sha})\n"
        f"% {t_path.relative_to(REPO)} (sha256 {t_sha})\n"
        f"% rendered from codebook v{cb['version']} (sha256 {cb['sha256']}). Verbatim; do not edit by hand.\n"
    )
    wrap_open = "{\\ttfamily\\footnotesize\\setlength{\\parindent}{0pt}\\setlength{\\parskip}{0pt}\\raggedright\n"
    wrap_close = "\n}\n"
    out = [head]
    out.append("\\subsubsection*{System prompt (\\texttt{system-prompt\\_v1.0.txt}, "
               f"{len(p_raw.decode('utf-8').splitlines())} lines).}}\n")
    out.append(wrap_open + block(p_raw.decode("utf-8")) + wrap_close)
    out.append("\n\\subsubsection*{Tool configuration (\\texttt{tool-config\\_v1.0.json}, "
               f"{len(t_raw.decode('utf-8').splitlines())} lines).}}\n")
    out.append(wrap_open + block(t_raw.decode("utf-8")) + wrap_close)
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="re-render and compare with the file on disk")
    ap.add_argument("--date", default=None, help="date for the provenance header (default: today)")
    args = ap.parse_args()
    today = args.date or date.today().isoformat()
    text = render(today)
    if args.check:
        on_disk = OUT.read_text(encoding="utf-8")
        # the date line is provenance, not content: compare everything below the header
        strip = lambda s: "\n".join(l for l in s.splitlines() if not l.startswith("% Generated by"))
        if strip(on_disk) != strip(text):
            sys.exit(f"{OUT.relative_to(REPO)} differs from a fresh render of the pinned artefacts")
        print(f"{OUT.relative_to(REPO)} matches the pinned artefacts")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(text):,} characters)")


if __name__ == "__main__":
    main()
