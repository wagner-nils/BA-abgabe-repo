#!/usr/bin/env python3
"""Evidence computations of the fourth review (pre-analysis specification §4p and its addendum, declared 2026-11-11
before any of them was computed; first run as scratch scripts for the review, moved here on 2026-11-11 so that every
figure the thesis takes from them is regenerated by the repository).

  (1)/(13) lexical baseline for technology detection (the prefilter's keyword matches, text-free file
           tools/annotation/labels/A2_prefilter_matches.json);
  (2)      the twelve configurations' first executions against the second coding (120 and the registered 40);
  (3)/(12) technology detection by language on valid first executions; missed rows by failed and valid output;
  (4)/(11) design-based intervals of the displacements; displacement against the second coding;
  (5)      the no-frame decision;  (6)/(10) the coder's retest in the model's metrics;  (9) hits and misses by whether
  the second coding keeps the tuple;  (7) direction of the share differences under the second coding;
  (8) majority baseline for evaluation;  (14) evaluation values and the speaker field;  (15) article A010;
  (16) element tuples per paragraph.

Descriptive, test-set reuse, nothing selected, no model call; the registered run, its tables and all labels are
untouched. Inputs load through the verified paths of evaluate.py, compare_models.py and review_analyses.py.

    .venv/bin/python3 tools/pipeline/review_checks_4p.py [--check]

Writes tools/runs/tables/review_checks_4p/results.json and paper/tables/tab_checks_4p.tex.
"""
from __future__ import annotations

import argparse
import csv
import json
import random
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import compare_models as cm                                         # noqa: E402
import evaluate as ev                                               # noqa: E402
import figures as fg                                                # noqa: E402
import review_analyses as ra                                        # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "tools" / "runs" / "tables" / "review_checks_4p"
TEX = ROOT / "paper" / "tables" / "tab_checks_4p.tex"
B, SEED = ra.B, ra.SEED


def compute() -> dict:
    out = {}
    inp, S, m = ra.load_registered()
    pids = S["pids"]; W = S["w"]; ART = S["art"]; LANG = S["lang"]
    arts = sorted({ART[p] for p in pids})
    base = {a: 1 for a in arts}
    pids40, ra40, rb40 = ra.recode_inputs(inp, S, m)
    w2 = ra.wave2_inputs(inp, S)
    second = dict(rb40); second.update(w2["rb"])           # second coding, all 120 paragraphs
    first = S["gold"]; pred1 = S["pred"].get(1, {})
    def pct(d):
        d = sorted(v for v in d if v is not None); q = lambda p: d[int(round(p * (len(d) - 1)))]
        return [q(0.025), q(0.975)] if d else [None, None]

    # ---- (1) lexical baseline
    MATCH = json.loads((ROOT / "tools/annotation/labels/A2_prefilter_matches.json").read_text(encoding="utf-8"))["matches"]
    def lex(pid, joint):
        hits = set(MATCH[pid]); res = hits - {"other"}
        if "other" in hits and joint: res |= {"other_renewable", "storage"}
        return res
    def tech_score(predset, classes, ps=pids):
        tp = fp = fn = 0.0; per = defaultdict(lambda: [0.0, 0.0, 0.0])
        for p in ps:
            g = {k[1] for k in first if k[0] == p} & classes; q = predset(p) & classes
            for c_ in classes:
                a, b = c_ in g, c_ in q
                per[c_][0] += W[p] * (a and b); per[c_][1] += W[p] * (b and not a); per[c_][2] += W[p] * (a and not b)
        tp = sum(v[0] for v in per.values()); fp = sum(v[1] for v in per.values()); fn = sum(v[2] for v in per.values())
        f = lambda t, a, b: 2 * t / (2 * t + a + b) if 2 * t + a + b else None
        return {"precision": tp / (tp + fp), "recall": tp / (tp + fn), "f1": f(tp, fp, fn), "per_class_f1": {c_: f(*v) for c_, v in sorted(per.items())}}
    five = {"general", "solar", "wind", "hydrogen", "nuclear"}; seven = five | {"other_renewable", "storage"}
    model_set = lambda p: {k[1] for k in pred1 if k[0] == p}
    out["lexical_baseline"] = {"five_classes": {"lexicon": tech_score(lambda p: lex(p, False), five), "model": tech_score(model_set, five)},
                               "seven_classes_joint_pattern": {"lexicon": tech_score(lambda p: lex(p, True), seven), "model": tech_score(model_set, seven)}}

    # ---- (2) recurrence against the second coding
    comp = json.loads((ROOT / "tools/runs/tables/model_comparison/comparison.json").read_text())
    rows = []
    for r in comp["rows"]["A2"]:
        if "request" in r["model"]: continue
        run = cm.load(r["run_id"], "A2"); P1 = run["S"]["pred"].get(1, {})
        rec = {"model": r["model"]}
        for name, gold, ps in (("first_120", first, pids), ("second_120", second, pids), ("first_40", {k: v for k, v in first.items() if k[0] in set(pids40)}, pids40), ("second_40", rb40, pids40)):
            T = {"gold": gold, "pred": {1: {k: v for k, v in P1.items() if k[0] in set(ps)}}, "w": W, "art": ART}
            pa = ev.counts_execution(T, ps, 1)["per_art"]; a_ = sorted({ART[p] for p in ps})
            pr, rc = cm._pr(pa, {a: 1 for a in a_})
            rng = random.Random(SEED); dr = []
            for _ in range(B):
                mu = Counter(rng.choice(a_) for _ in a_); x, y = cm._pr(pa, mu); dr.append(None if x is None or y is None else x - y)
            rec[name] = {"precision": pr, "recall": rc, "gap": pr - rc, "gap_iv": pct(dr)}
        rows.append(rec)
    out["recurrence"] = {"rows": rows, "positive_gaps": {k: sum(1 for r in rows if r[k]["gap"] > 0) for k in ("first_120", "second_120", "first_40", "second_40")},
                         "gap_interval_above_zero": {k: sum(1 for r in rows if r[k]["gap_iv"][0] > 0) for k in ("first_120", "second_120", "first_40", "second_40")}}

    # ---- (3) technology contrast on valid outputs; failures as paragraphs
    out1 = S["outcome"].get(1, {}); valid = [p for p in pids if out1.get(p) in ev.SUCCESS]
    per = {}; ar = {}
    for L in ("de", "en"):
        ps = [p for p in valid if S["lang"][p] == L]; per[L] = ev.counts_execution(S, ps, 1)["per_art"]; ar[L] = sorted({ART[p] for p in ps})
    pt = {L: ev.micro(per[L], "technology", {a: 1 for a in ar[L]}, True) for L in ("de", "en")}
    rng = random.Random(SEED); dr = []
    for _ in range(B):
        mu = {L: Counter(rng.choice(ar[L]) for _ in ar[L]) for L in ("de", "en")}
        dr.append(ev.micro(per["de"], "technology", mu["de"], True) - ev.micro(per["en"], "technology", mu["en"], True))
    term = list(csv.DictReader(open(ROOT / f"tools/runs/{ra.REG}_terminal.csv", encoding="utf-8"), delimiter=";"))
    failp = defaultdict(set)
    for r in term:
        if r["outcome"] not in ev.SUCCESS: failp[r["lang"]].add(r["paragraph_id"])
    out["technology_valid_only"] = {"de": pt["de"], "en": pt["en"], "diff": pt["de"] - pt["en"], "iv": pct(dr), "n_valid": {L: sum(1 for p in valid if S["lang"][p] == L) for L in ("de", "en")},
                                    "failed_paragraphs": {L: len(v) for L, v in failp.items()}, "failed_articles": {L: len({ART[p] for p in v}) for L, v in failp.items()}}

    # ---- (4) design-based intervals for the displacements
    stored = json.loads((ROOT / "tools/runs/tables/dsl/dsl_prevalence.json").read_text())["classes"]
    disp = {r["class"]: r for r in csv.DictReader(open(ROOT / f"tools/runs/tables/{ra.REG}/table5_displacement.csv"), delimiter=";") if r["population"] == "pooled"}
    d4 = {}
    for e in ev.ELEMENTS:
        c_ = stored.get("element:" + e)
        if not c_ or not c_["reported"]: continue
        d = c_["registered_displacement_pp"]; se = c_["se_design_pp"]
        iv_a = [float(x) for x in re.findall(r"-?\d+\.\d+", disp["element:" + e]["interval"])]
        d4[e] = {"displacement_pp": d, "design_iv": [d - 1.96 * se, d + 1.96 * se], "article_iv": iv_a}
    ex = lambda iv: iv[0] > 0 or iv[1] < 0
    out["displacement_intervals"] = {"elements": d4, "excluding_zero": {"design": sorted(e for e, v in d4.items() if ex(v["design_iv"])), "article": sorted(e for e, v in d4.items() if ex(v["article_iv"]))}}

    # ---- (5) the no-frame decision
    def unframed(rel): return sum(1 for v in rel.values() if not v.elements), len(rel)
    matched = [k for k in first if k in pred1]
    tp = sum(1 for k in matched if first[k].elements and pred1[k].elements); fp = sum(1 for k in matched if not first[k].elements and pred1[k].elements)
    fn = sum(1 for k in matched if first[k].elements and not pred1[k].elements); tn = len(matched) - tp - fp - fn
    miss_empty = miss_some = 0
    for k in matched:
        for e in first[k].elements:
            if e not in pred1[k].elements:
                if pred1[k].elements: miss_some += 1
                else: miss_empty += 1
    out["no_frame"] = {"unframed_rows": {"first_coding": unframed(first), "second_coding": unframed(second), "model_execution_1": unframed(pred1)},
                       "framed_decision_on_matched_rows": {"rows": len(matched), "tp": tp, "fp": fp, "fn": fn, "tn": tn, "precision": tp / (tp + fp), "recall": tp / (tp + fn)},
                       "misses_within_matched_rows": {"row_left_without_any_element": miss_empty, "row_with_at_least_one_element": miss_some}}

    # ---- (6) same-metric retest for technology and evaluation
    def scores(gold, pred, ps):
        T = {"gold": {k: v for k, v in gold.items() if k[0] in set(ps)}, "pred": {1: {k: v for k, v in pred.items() if k[0] in set(ps)}}, "w": W, "art": ART}
        cnt = ev.counts_execution(T, ps, 1); a_ = {a: 1 for a in {ART[p] for p in ps}}
        units = [u for us in cnt["A_units"]["evaluation_A"].values() for u in us]
        acc = sum(u[0] * u[1] for u in units) / sum(u[0] for u in units) if units else None
        return {"technology_f1": ev.micro(cnt["per_art"], "technology", a_, True), "element_f1": ev.micro(cnt["per_art"], "element", a_, True),
                "evaluation_matched_accuracy": acc, "matched_frame_units": len(units)}
    out["same_metric"] = {"wave1_40": {"first_vs_second": scores(rb40, first, pids40), "model_vs_second": scores(rb40, pred1, pids40), "model_vs_first": scores(first, pred1, pids40)},
                          "both_waves_120": {"first_vs_second": scores(second, first, pids), "model_vs_second": scores(second, pred1, pids), "model_vs_first": scores(first, pred1, pids)}}

    # ---- (7) displacement direction under the second coding
    def share(rel, e): return 100 * sum(W[p] for p in pids if any(k[0] == p and e in v.elements for k, v in rel.items())) / sum(W[p] for p in pids)
    byp = lambda rel: rel
    d7 = {}
    for e in d4:
        sm, s1, s2 = share(pred1, e), share(first, e), share(second, e)
        d7[e] = {"model": sm, "first": s1, "second": s2, "model_minus_first": sm - s1, "model_minus_second": sm - s2}
    out["direction_second_coding"] = {"elements": d7, "negative_vs_first": sum(1 for v in d7.values() if v["model_minus_first"] < -1e-9), "negative_vs_second": sum(1 for v in d7.values() if v["model_minus_second"] < -1e-9),
                                      "positive_vs_second": sum(1 for v in d7.values() if v["model_minus_second"] > 1e-9)}

    # ---- (8) majority baseline for matched-frame evaluation accuracy
    cnt = ev.counts_execution(S, pids, 1); units = [u for us in cnt["A_units"]["evaluation_A"].values() for u in us]
    wc = Counter()
    for u in units: wc[u[2]] += u[0]
    out["evaluation_majority_baseline"] = {"units": len(units), "modal_value": max(wc, key=wc.get), "weighted_share": max(wc.values()) / sum(wc.values()),
                                           "model_accuracy": sum(u[0] * u[1] for u in units) / sum(u[0] for u in units)}

    def boot(fn, arts):
        rng = random.Random(SEED); return pct([fn(Counter(rng.choice(arts) for _ in arts)) for _ in range(B)])
    r3 = lambda x: None if x is None else round(x, 4)
    # (9)
    def crosstab(ps):
        ps = set(ps); res = Counter(); wres = Counter()
        for k, g in first.items():
            if k[0] not in ps: continue
            p = pred1.get(k); s = second.get(k)
            for e in g.elements:
                hit = p is not None and e in p.elements
                kept = "kept" if (s is not None and e in s.elements) else ("row absent in second" if s is None else "element dropped in second")
                res[("hit" if hit else "miss", kept)] += 1; wres[("hit" if hit else "miss", kept)] += W[k[0]]
        return {f"{a} / {b}": [n, round(wres[(a, b)], 1)] for (a, b), n in sorted(res.items())}
    out["hits_misses_by_second_coding"] = {"wave1_40": crosstab(pids40), "all_120": crosstab(pids)}
    # (10)
    def frame_units(rel, ps, with_eval):
        u = defaultdict(float)
        for k, v in rel.items():
            if k[0] in ps:
                for fr, val in v.evals.items() if hasattr(v, "evals") else []:
                    u[(k[0], k[1], fr, val) if with_eval else (k[0], k[1], fr)] = W[k[0]]
        return u
    attr = [a for a in dir(next(iter(first.values()))) if not a.startswith("_")]
    def frame_f1(gold, pred, ps, with_eval):
        ps = set(ps); arts = sorted({ART[p] for p in ps})
        def units(rel):
            d = defaultdict(set)
            for k, v in rel.items():
                if k[0] in ps:
                    ev_map = getattr(v, "evaluations", None) or getattr(v, "evals", None) or {}
                    for fr, val in dict(ev_map).items(): d[ART[k[0]]].add((k[0], k[1], fr, val) if with_eval else (k[0], k[1], fr))
            return d
        g, q = units(gold), units(pred)
        def f(mu):
            tp = fp = fn = 0.0
            for a, mlt in mu.items():
                for x in g.get(a, set()) | q.get(a, set()):
                    w = W[x[0]] * mlt; tp += w * (x in g.get(a, ()) and x in q.get(a, ())); fp += w * (x not in g.get(a, ()) and x in q.get(a, ())); fn += w * (x in g.get(a, ()) and x not in q.get(a, ()))
            return 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else None
        return {"f1": r3(f({a: 1 for a in arts})), "iv": boot(f, arts), "units_reference": sum(len(v) for v in g.values()), "units_other": sum(len(v) for v in q.values())}
    out["derived_frames"] = {name: {"frame_presence": {"first_vs_second": frame_f1(sec, first, ps, False), "model_vs_second": frame_f1(sec, pred1, ps, False), "model_vs_first": frame_f1(first, pred1, ps, False)},
                                    "frame_evaluation": {"first_vs_second": frame_f1(sec, first, ps, True), "model_vs_second": frame_f1(sec, pred1, ps, True), "model_vs_first": frame_f1(first, pred1, ps, True)}}
                             for name, sec, ps in (("wave1_40", rb40, pids40), ("all_120", second, pids))}
    # (11)
    arts = sorted({ART[p] for p in pids}); byart = defaultdict(list)
    for p in pids: byart[ART[p]].append(p)
    def has(rel, p, e): return any(k[0] == p and e in v.elements for k, v in rel.items())
    ind = {e: {p: (has(pred1, p, e), has(first, p, e), has(second, p, e)) for p in pids} for e in ev.ELEMENTS}
    d11 = {}
    for e in ev.ELEMENTS:
        def f(mu, ref):
            num = sum(mu[a] * W[p] * (ind[e][p][0] - ind[e][p][ref]) for a in mu for p in byart[a]); den = sum(mu[a] * W[p] for a in mu for p in byart[a])
            return 100 * num / den
        base = {a: 1 for a in arts}
        sup2 = sum(ind[e][p][2] for p in pids); sup1 = sum(ind[e][p][1] for p in pids)
        if sup1 < 5: continue
        d11[e] = {"vs_first": r3(f(base, 1)), "iv_first": boot(lambda mu: f(mu, 1), arts), "vs_second": r3(f(base, 2)), "iv_second": boot(lambda mu: f(mu, 2), arts), "support_first": sup1, "support_second": sup2}
    exz = lambda iv: iv[0] > 0 or iv[1] < 0
    out["displacement_second_coding"] = {"elements": d11, "excluding_zero_vs_first": sorted(e for e, v in d11.items() if exz(v["iv_first"])), "excluding_zero_vs_second": sorted(e for e, v in d11.items() if exz(v["iv_second"])),
                                         "second_support_below_5": sorted(e for e, v in d11.items() if v["support_second"] < 5)}
    # (12)
    t12 = {}
    for L in ("de", "en"):
        c = Counter(); wc = Counter()
        for p in pids:
            if LANG[p] != L: continue
            g = {k[1] for k in first if k[0] == p}; q = {k[1] for k in pred1 if k[0] == p}; failed = out1.get(p) not in ev.SUCCESS
            for t in sorted(g | q):          # sorted: the counters' key order must not depend on the hash seed (M22)
                key = "tp" if (t in g and t in q) else "fp" if t in q else ("fn_failed_paragraph" if failed else "fn_valid_output")
                c[key] += 1; wc[key] += W[p]
        vp = wc["tp"] / (wc["tp"] + wc["fp"]); vr = wc["tp"] / (wc["tp"] + wc["fn_valid_output"])
        t12[L] = {"counts": dict(c), "weighted": {k: round(v, 1) for k, v in wc.items()}, "valid_only_precision": r3(vp), "valid_only_recall": r3(vr)}
    out["technology_by_language"] = t12
    # (13)
    five = {"general", "solar", "wind", "hydrogen", "nuclear"}
    lexs = {p: set(MATCH[p]) & five for p in pids}
    mods = {p: {k[1] for k in pred1 if k[0] == p} & five for p in pids}
    def tf1(predmap, gold, mu, ps=None):
        tp = fp = fn = 0.0
        for a, mlt in mu.items():
            for p in byart[a]:
                if ps is not None and p not in ps: continue
                g = {k[1] for k in gold if k[0] == p} & five; q = predmap[p]; w = W[p] * mlt
                tp += w * len(g & q); fp += w * len(q - g); fn += w * len(g - q)
        return 2 * tp / (2 * tp + fp + fn) if 2 * tp + fp + fn else None
    base = {a: 1 for a in arts}
    l13 = {"vs_first": {"lexicon": r3(tf1(lexs, first, base)), "model": r3(tf1(mods, first, base)), "model_minus_lexicon": r3(tf1(mods, first, base) - tf1(lexs, first, base)),
                        "iv": boot(lambda mu: tf1(mods, first, mu) - tf1(lexs, first, mu), arts)},
           "vs_second": {"lexicon": r3(tf1(lexs, second, base)), "model": r3(tf1(mods, second, base))}}
    for L in ("de", "en"):
        ps = {p for p in pids if LANG[p] == L}; l13[L] = {"lexicon": r3(tf1(lexs, first, base, ps)), "model": r3(tf1(mods, first, base, ps))}
    out["lexical_baseline_five_classes"] = l13
    # (14)
    def evdist(rel):
        c = Counter()
        for v in rel.values():
            for fr, val in dict(getattr(v, "evaluations", None) or getattr(v, "evals", None) or {}).items(): c[val] += 1
        return dict(c)
    out["evaluation_distribution"] = {"first": evdist(first), "second": evdist(second), "model": evdist(pred1)}
    rows = list(csv.DictReader(open(ROOT / "tools/annotation/labels/A2_pass2_v1.0.csv", encoding="utf-8-sig"), delimiter=";"))
    out["speaker_field_first_coding"] = dict(Counter(r["speaker"] or "(blank)" for r in rows))
    spk = {(r["paragraph_id"], r["technology"]): (r["speaker"] or "(blank)") for r in rows}
    cnt = ev.counts_execution(S, pids, 1)
    conf = Counter(); bys = defaultdict(lambda: [0.0, 0.0, 0])
    for key, us in cnt["A_units"]["evaluation_A"].items():
        for u in us: conf[(u[2], u[3])] += 1
    out["evaluation_confusion_coder_by_model"] = {f"{a} -> {b}": n for (a, b), n in sorted(conf.items())}
    # (15)
    a010 = {}
    for p in ("A010_p13", "A010_p18"):
        g = {k[1]: sorted(v.elements) for k, v in first.items() if k[0] == p}; q = {k[1]: sorted(v.elements) for k, v in pred1.items() if k[0] == p}; s2 = {k[1]: sorted(v.elements) for k, v in second.items() if k[0] == p}
        a010[p] = {"weight": W[p], "first": g, "second": s2, "model": q}
    out["a010_sampled_paragraphs"] = a010
    # (16)
    a3 = cm.load("a3_sonnet_20261019", "A3")["S"]
    def dens(rel, ps, lang):
        res = {}
        for L in ("de", "en"):
            pp = [p for p in ps if lang[p] == L]; res[L] = [sum(len(v.elements) for k, v in rel.items() if k[0] in set(pp)), len(pp)]
        return res
    out["tuples_per_paragraph"] = {"first": dens(first, pids, LANG), "second": dens(second, pids, LANG), "census": dens(a3["gold"], a3["pids"], a3["lang"])}
    return out


# --------------------------------------------------------------------------- output
def f3(x): return "---" if x is None else f"{x:.3f}"
def sg(x, d=3): return "---" if x is None else f"${'+' if x >= 0 else '-'}{abs(x):.{d}f}$"
def iv(t, d=3): return "" if not t or t[0] is None else f" [{t[0]:.{d}f}, {t[1]:.{d}f}]"
def siv(t, d=3): return "" if not t or t[0] is None else f" [{sg(t[0], d)}, {sg(t[1], d)}]"


